
import os
from io import BytesIO
from datetime import datetime

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
    HRFlowable
)


def generate_pdf_report(analysis: dict) -> BytesIO:
    buffer = BytesIO()

    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=18 * mm,
        leftMargin=18 * mm,
        topMargin=18 * mm,
        bottomMargin=18 * mm
    )

    styles = getSampleStyleSheet()

    styles.add(ParagraphStyle(
        name="ReportTitle",
        parent=styles["Title"],
        fontSize=23,
        textColor=colors.HexColor("#5145CD"),
        spaceAfter=8
    ))

    styles.add(ParagraphStyle(
        name="SectionHeading",
        parent=styles["Heading2"],
        textColor=colors.HexColor("#5145CD"),
        spaceBefore=14,
        spaceAfter=8
    ))

    story = []

    story.append(Paragraph("NeuroNexus AI", styles["ReportTitle"]))
    story.append(Paragraph(
        "Resume Analysis Report",
        styles["Heading2"]
    ))

    story.append(Spacer(1, 8))
    story.append(HRFlowable(
        width="100%",
        color=colors.HexColor("#5145CD")
    ))
    story.append(Spacer(1, 12))

    filename = analysis.get("filename", "Resume")
    job_description = analysis.get("job_description", "Not provided")

    story.append(Paragraph(
        f"<b>Resume:</b> {filename}",
        styles["Normal"]
    ))

    story.append(Paragraph(
        f"<b>Generated:</b> {datetime.now().strftime('%d %B %Y, %I:%M %p')}",
        styles["Normal"]
    ))

    story.append(Spacer(1, 15))
    story.append(Paragraph("Analysis Scores", styles["SectionHeading"]))

    score_data = [
        ["Metric", "Score"],
        ["Overall Score", f"{analysis.get('overall_score', 0)}%"],
        ["Semantic Similarity", f"{analysis.get('semantic_similarity', 0)}%"],
        ["Skill Match", f"{analysis.get('skill_match', 0)}%"]
    ]

    score_table = Table(score_data, colWidths=[100 * mm, 55 * mm])

    score_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#5145CD")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.lightgrey),
        ("PADDING", (0, 0), (-1, -1), 9),
        ("BACKGROUND", (0, 1), (-1, -1), colors.HexColor("#F4F3FF"))
    ]))

    story.append(score_table)

    story.append(Paragraph("Matched Skills", styles["SectionHeading"]))

    matched = analysis.get("matched_skills", [])
    story.append(Paragraph(
        ", ".join(matched) if matched else "No matched skills found.",
        styles["Normal"]
    ))

    story.append(Paragraph("Missing Skills", styles["SectionHeading"]))

    missing = analysis.get("missing_skills", [])
    story.append(Paragraph(
        ", ".join(missing) if missing else "No missing skills identified.",
        styles["Normal"]
    ))

    story.append(Paragraph("Job Description", styles["SectionHeading"]))
    story.append(Paragraph(
        job_description.replace("\n", "<br/>"),
        styles["Normal"]
    ))

    story.append(Spacer(1, 20))
    story.append(HRFlowable(width="100%", color=colors.lightgrey))
    story.append(Spacer(1, 8))

    story.append(Paragraph(
        "Generated by NeuroNexus AI | AI-powered Resume Analyzer",
        styles["Italic"]
    ))

    doc.build(story)
    buffer.seek(0)

    return buffer
